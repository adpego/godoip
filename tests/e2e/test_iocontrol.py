from conftest import nrc


def test_short_term_adjustment_and_return(uds):
    uds([0x10, 0x03])
    assert uds([0x2F, 0x05, 0x00, 0x03, 0x64]) == bytes([0x6F, 0x05, 0x00, 0x03, 0x64])
    assert uds([0x22, 0x05, 0x00]) == bytes([0x62, 0x05, 0x00, 0x64])
    assert uds([0x2F, 0x05, 0x00, 0x00]) == bytes([0x6F, 0x05, 0x00, 0x00, 0x1E])


def test_reset_to_default(client):
    client.change_session(3)
    resp = client.io_control(0x0500, control_param=0x01)
    assert resp.service_data.did_echo == 0x0500
    assert resp.service_data.decoded_data == (0x00,)


def test_control_released_on_default_session(uds):
    uds([0x10, 0x03])
    uds([0x2F, 0x05, 0x00, 0x03, 0x64])
    uds([0x10, 0x01])
    assert uds([0x22, 0x05, 0x00]) == bytes([0x62, 0x05, 0x00, 0x1E])


def test_not_in_default_session(uds):
    assert uds([0x2F, 0x05, 0x00, 0x03, 0x64]) == nrc(0x2F, 0x7F)
