from conftest import nrc


def test_on_change_of_did(uds):
    # Respond with ReadDataByIdentifier 0x0101 when it changes.
    setup = [0x86, 0x03, 0x02, 0x01, 0x01, 0x22, 0x01, 0x01]
    assert uds(setup) == bytes([0xC6, 0x03, 0x00, 0x02, 0x01, 0x01, 0x22, 0x01, 0x01])
    assert uds([0x86, 0x05, 0x02]) == bytes([0xC6, 0x05, 0x00, 0x02])
    assert uds([0x2E, 0x01, 0x01] + list(b"EVENT")) == bytes([0x6E, 0x01, 0x01])
    assert uds.receive() == bytes([0x62, 0x01, 0x01]) + b"EVENT"
    assert uds([0x86, 0x06, 0x02]) == bytes([0xC6, 0x06, 0x01, 0x02])


def test_on_timer(uds):
    assert uds([0x86, 0x02, 0x02, 0x03, 0x22, 0xF1, 0x89])[0] == 0xC6
    assert uds([0x86, 0x05, 0x02])[0] == 0xC6
    for _ in range(2):
        assert uds.receive() == bytes([0x62, 0xF1, 0x89, 0x01, 0x02, 0x03])
    assert uds([0x86, 0x00, 0x02])[:2] == bytes([0xC6, 0x00])


def test_start_without_events(uds):
    assert uds([0x86, 0x05, 0x02]) == nrc(0x86, 0x24)
